#!/usr/bin/env python3
"""Exploded render of the nRF54L15 coin-cell trigger: floor, cell, PCB, shell.

Rebuilds docs/img/case-pcb.png from the current geometry.

    docs/render/render.sh

Inputs, git-ignored and regenerated by render.sh:

    case/stl/*.stl
    kicad/out/openrz67-nrf.glb
        kicad-cli pcb export glb --user-origin 0x0mm  (board corner = origin)

Geometry notes
--------------
The case STLs share one assembly origin (mm, Z up). The board hangs in the
shell component side up, turned 180 degrees about Z, so board X runs right to
left (as in case/view.py):

    case x = BOARD_X0 - board x
    case y = BOARD_Y0 + board y
    case z = PCB_Z                    (board bottom)

The CR2032 has no KiCad model; it is a plain cylinder under the clip. Keep the
constants in sync with case/openrz67_nrf_case.py.
"""

import math
import os
import sys
from pathlib import Path

import bpy

sys.path.insert(0, str(Path(__file__).resolve().parent))
from render_common import (  # noqa: E402
    HERE, REPO, C_CASE, C_TEXT, assign, clear_scene, import_glb, import_stl, mat, move,
    shade_smooth, shoot,
)

STL = REPO / "case" / "stl"
GLB = REPO / "kicad" / "out" / "openrz67-nrf.glb"
OUT = Path(os.environ.get("RENDER_OUT", REPO / "docs" / "img" / "case-pcb.png"))

# wall + clr + board_w, wall + ant_wall_clr + clr, floor_t + clip_h + clip_gap
BOARD_X0, BOARD_Y0, PCB_Z = 33.3, 4.8, 5.45
# BT1 centre (13.5, 18) in case coordinates; the cell ends 0.1 under the board
CELL_C, CELL_D, CELL_T = (19.8, 22.8), 20.0, 3.2

# Exploded lift per group, mm. The cell must clear the floor's back band below
# and the clip above, the shell the tallest part on the board.
LIFT_CELL = 12.0
LIFT_PCB = 26.0
LIFT_LID = 56.0


def cell():
    z0 = PCB_Z - 0.1 - CELL_T
    bpy.ops.mesh.primitive_cylinder_add(
        vertices=128, radius=CELL_D / 2, depth=CELL_T,
        location=(*CELL_C, z0 + CELL_T / 2))
    o = bpy.context.object
    o.name = "cr2032"
    bev = o.modifiers.new("bevel", "BEVEL")
    bev.width = 0.35
    bev.segments = 4
    bev.limit_method = "ANGLE"
    bpy.ops.object.shade_smooth()
    assign([o], mat("cell", (0.78, 0.78, 0.76), rough=0.28, metallic=1.0))
    return [o]


def main():
    clear_scene()

    missing = [p for p in (STL / "openrz67-nrf-base.stl", GLB) if not p.exists()]
    if missing:
        raise SystemExit(
            "missing input(s):\n  " + "\n  ".join(str(m) for m in missing)
            + "\n\nRun ./render.sh nrf, which regenerates them."
        )

    base = import_stl(STL / "openrz67-nrf-base.stl")
    lid = import_stl(STL / "openrz67-nrf-lid.stl")
    pipe = import_stl(STL / "openrz67-nrf-lightpipe.stl")
    text = import_stl(STL / "openrz67-nrf-lid-text.stl")

    m_case = mat("case", C_CASE, rough=0.62)
    m_pipe = mat("lightpipe", (0.92, 0.94, 0.95), rough=0.12)
    pn = m_pipe.node_tree.nodes["Principled BSDF"]
    pn.inputs["Transmission Weight"].default_value = 0.75
    pn.inputs["IOR"].default_value = 1.5

    assign(base + lid, m_case)
    assign(text, mat("lid-text", C_TEXT, rough=0.58))
    assign(pipe, m_pipe)
    shade_smooth(base + lid + pipe + text)

    # KiCad glTF: metres, Y up, KiCad's Y negated. Scale to mm, turn 180 degrees
    # about Z (board x -> -x, board y -> +y), then put the corner at BOARD_X0/Y0.
    pcb = import_glb(GLB)
    roots = [o for o in pcb if o.parent is None]
    for o in roots:
        o.scale = (1000.0, 1000.0, 1000.0)
        o.rotation_mode = "XYZ"
        o.rotation_euler.z += math.pi
    move(roots, delta=(BOARD_X0, BOARD_Y0, PCB_Z))

    cr = cell()

    move(cr, dz=LIFT_CELL)
    move(roots, dz=LIFT_PCB)
    move(lid + pipe + text, dz=LIFT_LID)
    bpy.context.view_layer.update()

    shoot(base + cr + pcb + lid + pipe + text, OUT, HERE / "case-pcb.blend")


if __name__ == "__main__":
    main()
